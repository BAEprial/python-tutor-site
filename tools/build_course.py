def split_tags(raw: str) -> tuple[list[str], bool]:
    """Return (tags, is_local) from the compact tag string."""
    tags = [t.strip() for t in raw.split(",") if t.strip()]
    is_local = "local" in tags
    return [t for t in tags if t != "local"], is_local


